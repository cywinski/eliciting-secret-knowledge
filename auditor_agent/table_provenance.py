# ABOUTME: Maps every cell of the paper's agentic-auditing results (Section 6) to the run directories and judgment files
# ABOUTME: behind it, recomputing each number so the manifest fails loudly if it drifts from the paper.
import glob
import json
import os
import sys
from typing import Dict, List

import fire

sys.path.append(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from auditor_agent.detection_table import summarise  # noqa: E402

RESULTS = "output/auditor_agent"
ANALYSIS = f"{RESULTS}/analysis"

# (auditor, organism) -> per-condition run directories. Sampling and the two white-box conditions
# come from the original sweeps; prefill comes from the `paired50` sweep that replaced them.
SOURCES = {
    ("MiniMax-M2.7", "female"): {
        "default": ["user_gender_female_gender_prior10", "user_gender_female_gender_prior20"],
        "prefill": ["user_gender_female_mmdecoupled_paired50"],
        "detection": f"{ANALYSIS}/detection_n50_minimax_female.json",
        "detection_prefill": f"{ANALYSIS}/detection_paired_minimax_female.json",
    },
    ("MiniMax-M2.7", "male"): {
        "default": ["user_gender_male_gender_male_prior30"],
        "prefill": ["user_gender_male_mmdecoupled_paired50"],
        "detection": f"{ANALYSIS}/detection_n50_minimax_male.json",
        "detection_prefill": f"{ANALYSIS}/detection_paired_minimax_male.json",
    },
    ("GLM-5.2", "female"): {
        "default": ["user_gender_female_glm_glm_prior30"],
        "prefill": ["user_gender_female_glmdecoupled_paired50"],
        "detection": f"{ANALYSIS}/detection_n50_glm_female.json",
        "detection_prefill": f"{ANALYSIS}/detection_paired_glm_female.json",
    },
    ("GLM-5.2", "male"): {
        "default": ["user_gender_male_glm_glm_prior30"],
        "prefill": ["user_gender_male_glmdecoupled_paired50"],
        "detection": f"{ANALYSIS}/detection_n50_glm_male.json",
        "detection_prefill": f"{ANALYSIS}/detection_paired_glm_male.json",
    },
}

CONDS = ["sample_only", "prefill", "logit_lens", "sae"]
LABELS = {
    "sample_only": "I/O (sampling only)",
    "prefill": "I/O + assistant prefill",
    "logit_lens": "I/O + LL tokens",
    "sae": "I/O + SAE desc.",
}

# The numbers as they stand in the paper (Section 6, Figure 7), so the manifest is checked against it.
EXPECTED_SUCCESS = {
    ("MiniMax-M2.7", "sample_only"): (16, 100), ("GLM-5.2", "sample_only"): (79, 100),
    ("MiniMax-M2.7", "logit_lens"): (56, 100), ("GLM-5.2", "logit_lens"): (100, 100),
    ("MiniMax-M2.7", "sae"): (61, 100), ("GLM-5.2", "sae"): (98, 100),
    ("MiniMax-M2.7", "prefill"): (12, 100), ("GLM-5.2", "prefill"): (52, 100),
}
# mean turn and n, averaged over the successful investigations only, so n matches EXPECTED_SUCCESS
EXPECTED_TURNS = {
    ("MiniMax-M2.7", "sample_only"): (11.5, 16), ("GLM-5.2", "sample_only"): (7.7, 79),
    ("MiniMax-M2.7", "prefill"): (13.5, 12), ("GLM-5.2", "prefill"): (8.5, 52),
    ("MiniMax-M2.7", "logit_lens"): (9.1, 56), ("GLM-5.2", "logit_lens"): (2.9, 100),
    ("MiniMax-M2.7", "sae"): (8.0, 61), ("GLM-5.2", "sae"): (4.8, 98),
}


# The detection table averages over exactly the investigations counted as successes in the first
# table, so its n must equal that table's numerator cell for cell.
for _cell, (_k, _n) in EXPECTED_SUCCESS.items():
    assert EXPECTED_TURNS[_cell][1] == _k, (
        f"{_cell}: detection table says n={EXPECTED_TURNS[_cell][1]}, success table says {_k}"
    )


def _dirs(src: Dict, cond: str) -> List[str]:
    return src.get(cond, src["default"])


def _trials(src: Dict, cond: str) -> List[Dict]:
    """Per-trial summaries for one condition of one cell."""
    out = []
    for d in _dirs(src, cond):
        for p in sorted(glob.glob(f"{RESULTS}/{d}/{cond}/trial_*/summary.json")):
            with open(p, "r", encoding="utf-8") as f:
                out.append(json.load(f) | {"trial_dir": os.path.dirname(p)})
    return out


def _git_sha(trial_dir: str) -> str:
    """Commit that produced a trial, recorded by run_audit.py alongside the resolved config."""
    path = os.path.join(trial_dir, "config_resolved.json")
    if not os.path.exists(path):
        return "unknown"
    with open(path, "r", encoding="utf-8") as f:
        return (json.load(f).get("git_sha") or "unknown")[:9]


def main(output: str = f"{ANALYSIS}/TABLE_PROVENANCE.md"):
    """Write the cell-to-run-directory manifest, verifying every number it records.

    Args:
        output: Path of the markdown manifest to write.
    """
    lines = [
        "# Where the paper's agentic-auditing numbers (Section 6, Figure 7) come from",
        "",
        "Generated by `auditor_agent/table_provenance.py`, which recomputes every cell from the",
        "directories listed here and asserts it matches the paper. Re-run it after any change:",
        "a drift between the runs and the paper becomes an assertion failure, not a silent edit.",
        "",
        "Each trial directory holds `trajectory.json` (every probe, tool result and the auditor's",
        "reasoning), `report.json`, `judgment.json`, `summary.json`, `target_io.jsonl` and",
        "`auditor_io.jsonl`.",
        "",
        "## Success rate (table 1)",
        "",
        "A cell is one auditor x one organism x one method, n = 50. Where a cell was filled by two",
        "runs, each run's own trials are listed separately and the cell total is the sum.",
        "",
        "| method | auditor | organism | this run | cell | run directory | git |",
        "|---|---|---|---|---|---|---|",
    ]
    pooled: Dict = {}
    for cond in CONDS:
        for (auditor, organism), src in SOURCES.items():
            rows = _trials(src, cond)
            assert rows, f"no trials for {auditor}/{organism}/{cond}"
            k = sum(r["value_correct"] for r in rows)
            pooled.setdefault((auditor, cond), [0, 0])
            pooled[(auditor, cond)][0] += k
            pooled[(auditor, cond)][1] += len(rows)
            for d in _dirs(src, cond):
                here = [r for r in rows if r["trial_dir"].startswith(f"{RESULTS}/{d}/")]
                assert here, f"no trials under {d} for {cond}"
                lines.append(
                    f"| {LABELS[cond]} | {auditor} | {organism} | "
                    f"{sum(r['value_correct'] for r in here)}/{len(here)} | {k}/{len(rows)} | "
                    f"`{RESULTS}/{d}/{cond}/trial_*` | `{_git_sha(here[0]['trial_dir'])}` |"
                )

    lines += ["", "Pooled over both organisms, as reported in the paper:", "",
              "| method | auditor | correct / n | matches paper |", "|---|---|---|---|"]
    for (auditor, cond), (k, n) in sorted(pooled.items()):
        expected = EXPECTED_SUCCESS[(auditor, cond)]
        assert (k, n) == expected, f"{auditor}/{cond}: computed {k}/{n}, paper says {expected}"
        lines.append(f"| {LABELS[cond]} | {auditor} | {k}/{n} | yes |")

    lines += ["", "## Detection turn (table 2)", "",
              "Averaged over the investigations whose report named the value, so `n` matches the",
              "success-rate table above; see `auditor_agent/detection_table.py --successes_only`.",
              "", "| method | auditor | mean turn | n (= successes above) | judgment files | matches paper |",
              "|---|---|---|---|---|---|"]
    for cond in CONDS:
        for auditor in ["MiniMax-M2.7", "GLM-5.2"]:
            cells = [(o, s) for (a, o), s in SOURCES.items() if a == auditor]
            key = "detection_prefill" if cond == "prefill" else "detection"
            paths = ",".join(s[key] for _, s in cells)
            # the pre-`paired50` judgment files also hold prefill trials from superseded arms
            run_filter = "" if cond != "prefill" else "_paired50"
            got = summarise(paths, cond, run_filter, successes_only=True)
            expected = EXPECTED_TURNS[(auditor, cond)]
            assert (round(got["mean"], 1), got["n"]) == expected, (
                f"{auditor}/{cond}: computed {got['mean']:.1f} (n={got['n']}), paper says {expected}"
            )
            files = "<br>".join(f"`{p}`" for _, s in cells for p in [s[key]])
            lines.append(
                f"| {LABELS[cond]} | {auditor} | {got['mean']:.1f} | {got['n']}/{got['n_audits']} "
                f"| {files} | yes |"
            )

    lines += [
        "",
        "## Superseded, not used in the paper",
        "",
        "| run | why |",
        "|---|---|",
        "| `user_gender_*_glmcolon_prefill_colon*`, `user_gender_*_colon_prefill_colon*` | the earlier "
        "prefill arms, one bundled tool and no `sample` tool |",
        "| `user_gender_*_glmdecoupled_twotool50` | prefill returned only the continuation, so the arm "
        "saw fewer target responses than any other condition; killed at 70 trials |",
        "| `user_gender_*_glmdecoupled_{decoupled5,twotool5,notstated5}` | n=5 pilots while the tool "
        "was being designed |",
        "",
    ]

    os.makedirs(os.path.dirname(output), exist_ok=True)
    with open(output, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"wrote {output}; every cell recomputed and matched the paper")


if __name__ == "__main__":
    fire.Fire(main)
